const CHAR_WIDTH = 5;
const CHAR_HEIGHT = 7;
const CHAR_SPACING = 1;

/** Strips accents and drops anything outside the glyph table (replaced by space). */
function normalizeForFont(text) {
  return String(text ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .split('')
    .map((ch) => (GLYPHS[ch] ? ch : ' '))
    .join('')
    .replace(/ +/g, ' ')
    .trim();
}

function textWidth(text, scale) {
  const len = text.length;
  if (len === 0) return 0;
  return len * (CHAR_WIDTH * scale) + (len - 1) * (CHAR_SPACING * scale);
}

function drawChar(pixels, width, height, ch, x, y, scale, color) {
  const glyph = GLYPHS[ch] || GLYPHS[' '];
  for (let col = 0; col < CHAR_WIDTH; col++) {
    const bits = glyph[col];
    for (let row = 0; row < CHAR_HEIGHT; row++) {
      if (!(bits & (1 << row))) continue;
      const px0 = x + col * scale;
      const py0 = y + row * scale;
      for (let sy = 0; sy < scale; sy++) {
        const py = py0 + sy;
        if (py < 0 || py >= height) continue;
        for (let sx = 0; sx < scale; sx++) {
          const px = px0 + sx;
          if (px < 0 || px >= width) continue;
          const idx = (py * width + px) * 3;
          pixels[idx] = color[0];
          pixels[idx + 1] = color[1];
          pixels[idx + 2] = color[2];
        }
      }
    }
  }
}

/** Draws pre-normalized text (see normalizeForFont) left-to-right starting at (x, y). */
function drawText(pixels, width, height, text, x, y, scale, color) {
  let cx = x;
  const step = (CHAR_WIDTH + CHAR_SPACING) * scale;
  for (const ch of text) {
    drawChar(pixels, width, height, ch, cx, y, scale, color);
    cx += step;
  }
}

